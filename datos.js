// Obtener todos los equipos de todas las zonas
function obtenerTodosLosEquipos() {

    const equipos = [];

    Object.keys(datosLiga.zonas).forEach(zona => {

        datosLiga.zonas[zona].forEach(equipo => {

            equipos.push({
                nombre: equipo.equipo,
                zona: zona,
                pts: equipo.pts,
                pj: equipo.pj,
                pg: equipo.pg,
                pe: equipo.pe,
                pp: equipo.pp,
                gf: equipo.gf,
                gc: equipo.gc,
                dg: equipo.dg
            });

        });

    });

    return equipos;
}


// Buscar un equipo por nombre
function buscarEquipo(nombre) {

    const equipos = obtenerTodosLosEquipos();

    return equipos.find(
        equipo =>
            equipo.nombre.toLowerCase() === nombre.toLowerCase()
    );

}


// Obtener la tabla de una zona
function obtenerTabla(zona) {

    return datosLiga.zonas[zona] || [];

}


// Obtener partidos de una zona
function obtenerPartidosZona(zona) {

    return datosLiga.partidos.filter(
        partido => partido.zona === zona
    );

}


// Obtener partidos finalizados
function obtenerResultados() {

    return datosLiga.partidos.filter(
        partido => partido.estado === "finalizado"
    );

}


// Obtener próximos partidos
function obtenerProximosPartidos() {

    return datosLiga.partidos.filter(
        partido => partido.estado === "programado"
    );

}
